import { useEffect, useMemo } from 'react';
import { useTexture } from '@react-three/drei';
import * as THREE from 'three';
import { PALETTE } from './World';
import { SUN_COLOR, SUN_DIRECTION } from './environment';
import { buildDisc } from './disc';
import type { RegionDef } from '../catalog/regions';

/**
 * Sky and terrain colour.
 *
 * Both are colour-only changes on purpose. Walking is solved in two dimensions
 * against a flat plane (`navigation.ts` never reads a height), so terrain that
 * displaced its vertices would immediately disagree with where the player
 * actually stands. Vertex colours buy most of the visual gain for none of that
 * risk.
 */

/** Horizon tone. Fog is matched to this so distant land melts into the sky. */
export const HORIZON_COLOR = new THREE.Color('#253352');

/**
 * Ground textures, generated by `tools/blender/ground_texture.py`.
 *
 * Both are seamlessly tileable, so the disc can repeat them many times across
 * its radius without a grid of seams appearing through the ground.
 */
const NORMAL_MAP_URL = '/textures/ground_normal.png';
const ROUGH_MAP_URL = '/textures/ground_rough.png';

/**
 * World units covered by one texture tile.
 *
 * Too small and the grain reads as noise; too large and a 40-unit disc barely
 * shows two tiles, so the surface stays flat where the player can actually see
 * it. Six units puts a visible tooth underfoot while staying coarse enough not
 * to shimmer at distance.
 */
/**
 * World units per texture repeat.
 *
 * This is a viewing-distance number, not a taste one. The normal map is 512², the
 * camera sits about 4.7 units up, and the ground it stands on is three units
 * ahead — so at a tile of 6 one repeat spans **2540 screen pixels** and the map
 * lands at **0.20 texels per screen pixel**: a five-fold magnification, which is
 * why the ground reads smooth exactly where the player is looking down at it.
 *
 * At 2 the same map lands at 0.60 texels per pixel close in and is minified
 * rather than blown up further out, where anisotropy takes over. The risk is the
 * opposite failure — twenty repeats across an island and a wallpaper if the map
 * has a motif — so it was measured and looked at rather than argued.
 */
const GROUND_TILE_SIZE = 2;

/**
 * Strength of the ground's surface relief, in tangent-space slope.
 *
 * This is a module constant rather than an inline `new THREE.Vector2(...)`, and
 * that is not tidiness. With the literal inline, a `normalScale` written onto the
 * material from outside was back to its declared 0.55 within 50 ms — measured by
 * writing 8 and reading it back at 50, 300 and 1500 ms. With the value hoisted,
 * the same write survives 1200 ms untouched. What puts it back is not recorded
 * here; only the two ends of that measurement are.
 *
 * The consequence was worse than an untunable slider. Every attempt to price
 * this map at a stronger setting was measuring the unchanged scene and reporting
 * that the map did nothing, which is why 0.55 looked like a well-chosen number
 * for as long as it was there.
 *
 * The number itself is measured. At 0.55 the ground's rendered luminance was
 * indistinguishable from the same scene with no normal map at all — below the
 * difference between two consecutive frames — so the map was not doing its job.
 * Handing the same material a synthetic map proved the path was alive (13.04%
 * of the frame moved), which located the fault in the amplitude rather than in
 * the shader.
 *
 * **Re-measured after the tile size changed**, because the number below was
 * chosen against a map that was being magnified five times over. That rejection
 * does not survive: at a tile of 2 the relief scales both scales of the texture
 * together and the coarse-to-fine ratio *improves* as it rises.
 *
 * | relief | fine (21 px) | coarse (45 px) | ratio | mean luma |
 * | --- | --- | --- | --- | --- |
 * | 1.5 | 7.46 | 9.32 | 1.25 | 114.45 |
 * | **2.2** | **9.79** | **11.94** | **1.22** | 112.55 |
 * | 3.0 | 12.47 | 14.85 | 1.19 | 110.26 |
 *
 * 2.2 is +31% of the fine detail and keeps the ground reading as sand. 3.0 is
 * +67% and the ratio is no worse, so the old complaint — blotches rather than
 * grain — does not reproduce and should not be repeated. 3.0 is still wrong, for
 * a different reason that was not visible before: with the map resolving, the
 * tooth stops reading as sand and starts reading as gravel.
 */
const GROUND_NORMAL_SCALE = 2.2;

/**
 * The same value as a Vector2, built once.
 *
 * This is the object the JSX names, so what the material holds and what the
 * declaration says are the same thing rather than two copies of a number.
 */
const GROUND_NORMAL_SCALE_VECTOR = new THREE.Vector2(GROUND_NORMAL_SCALE, GROUND_NORMAL_SCALE);

/**
 * A vertical gradient dome.
 *
 * A flat background colour makes the world look like it is sitting inside a
 * box: the horizon becomes a hard line with nothing above it. A gradient gives
 * the sky depth, and gives the distant region discs something to fade into.
 *
 * `radius` must stay comfortably inside the camera's far plane (900, set in
 * `Scene.tsx`). A dome beyond it is not drawn at all, and the missing wedge
 * shows up as a hard dark triangle in the corner of the sky.
 */
export function SkyDome({ radius = 760 }: { radius?: number }) {
  const material = useMemo(
    () =>
      new THREE.ShaderMaterial({
        side: THREE.BackSide,
        depthWrite: false,
        // The dome is the backdrop. Fogging it would flatten the gradient back
        // to the fog colour and undo the whole point of it.
        fog: false,
        uniforms: {
          uZenith: { value: new THREE.Color(PALETTE.midnight) },
          uHorizon: { value: HORIZON_COLOR.clone() },
          uGlow: { value: new THREE.Color('#3f6a86') },
          // The visible sky was the one part of the scene with no idea where the
          // sun was. The environment probe puts its disc on SUN_DIRECTION and
          // the key light shines along it, so the shadows already said "warm
          // light from up and to the right" while the backdrop said nothing at
          // all. Same constant, so the three agree by construction.
          uSun: { value: SUN_DIRECTION.clone() },
          uSunColour: { value: SUN_COLOR.clone() },
        },
        vertexShader: `
          varying float vHeight;
          varying vec3 vDir;
          void main() {
            // Direction from the camera, so the gradient stays anchored to the
            // horizon instead of sliding with the dome.
            vec3 world = (modelMatrix * vec4(position, 1.0)).xyz;
            vDir = world - cameraPosition;
            vHeight = normalize(vDir).y;
            gl_Position = projectionMatrix * viewMatrix * vec4(world, 1.0);
          }
        `,
        fragmentShader: `
          uniform vec3 uZenith;
          uniform vec3 uHorizon;
          uniform vec3 uGlow;
          uniform vec3 uSun;
          uniform vec3 uSunColour;
          varying float vHeight;
          varying vec3 vDir;

          void main() {
            vec3 d = normalize(vDir);
            float h = clamp(vHeight, -1.0, 1.0);
            float t = pow(clamp(1.0 - h, 0.0, 1.0), 5.0);
            vec3 colour = mix(uZenith, uHorizon, t);
            // A faint lift where the sky meets the land, so the sun has a
            // visible source instead of arriving from nowhere.
            colour += uGlow * pow(t, 3.0) * 0.3;

            // The sun itself, and the wide warmth around it.
            float sun = max(dot(d, normalize(uSun)), 0.0);
            colour += uSunColour * (pow(sun, 90.0) * 0.9 + pow(sun, 6.0) * 0.1);

            // High cloud. Four sine terms over the view direction rather than a
            // noise function: it is continuous everywhere, needs no texture, and
            // costs a handful of ALU on the one surface that never writes depth.
            // Kept very low contrast — this is atmosphere, not a weather system.
            float band =
                sin(d.x * 3.1 + d.y * 1.7) * 0.50 +
                sin(d.z * 4.3 - d.y * 2.2) * 0.34 +
                sin((d.x + d.z) * 7.4 + d.y * 3.1) * 0.22 +
                sin((d.x - d.z) * 11.3 - d.y * 5.7) * 0.11;
            float cloud = smoothstep(0.18, 0.72, band);
            // Present above the horizon, gone before the zenith, brightest where
            // the haze already is.
            float mask =
                smoothstep(-0.02, 0.30, d.y) *
                (1.0 - smoothstep(0.55, 0.98, d.y)) *
                (0.35 + 0.65 * t);
            colour = mix(colour, colour + uGlow * 0.55, cloud * mask * 0.5);

            // A far ridge standing on the horizon.
            //
            // The world is eight coplanar discs. Measured from the hub, the
            // furthest of them never rises above y = 330 in a 1610-pixel frame
            // and is edge-confined throughout — past the nearest island there
            // is nothing at all, so the horizon is a hard line between land and
            // gradient. This is the one piece of the backdrop that is missing.
            //
            // Same idiom as the cloud above it, deliberately: sines over the
            // view direction, no texture, a handful of ALU on the one surface
            // that never writes depth. It is painted *into* the dome, so the
            // islands draw over it for free and no depth sorting is involved.
            float az = atan(d.z, d.x);
            float ridge =
                sin(az * 1.7) * 0.55 +
                sin(az * 3.3 + 1.1) * 0.28 +
                sin(az * 6.7 - 0.7) * 0.17;

            // Two ridges, because one band reads as a painted stripe and two
            // read as land going away. The far one is higher — on a flat world
            // the horizon is eye level, so distance lifts a silhouette toward
            // it — and paler, which is what haze does to it.
            float azF = az * 0.61 + 2.1;
            float ridgeFar =
                sin(azF * 1.3) * 0.55 +
                sin(azF * 2.9 + 0.6) * 0.29 +
                sin(azF * 5.3 - 1.4) * 0.16;
            float farTop = 0.036 + ridgeFar * 0.019;
            float farBand = smoothstep(farTop, farTop - 0.003, d.y) * smoothstep(-0.042, 0.004, d.y);
            colour = mix(colour, uHorizon * 0.88, farBand * 0.8);

            // The near ridge line, in units of view-direction height, so it sits
            // just above where the discs meet the sky and no higher.
            float ridgeTop = 0.030 + ridge * 0.014;
            float below = smoothstep(ridgeTop, ridgeTop - 0.004, d.y);
            // Only where the ground would be: fades out below the discs so the
            // void under an island is not filled in.
            float onLand = below * smoothstep(-0.045, 0.004, d.y);
            // Two tones, so the ridge is not one flat cut-out.
            float shade = smoothstep(ridgeTop - 0.010, ridgeTop - 0.002, d.y);
            colour = mix(colour, mix(uHorizon * 0.52, uHorizon * 0.78, shade), onLand * 0.92);

            gl_FragColor = vec4(colour, 1.0);
          }
        `,
      }),
    [],
  );

  return (
    <mesh material={material} renderOrder={-1000} frustumCulled={false}>
      <sphereGeometry args={[radius, 32, 16]} />
    </mesh>
  );
}

/**
 * A ground disc with per-vertex tint.
 *
 * Two low-frequency noises drive the colour: a broad drift so no two regions
 * read as the same slab of paint, and a finer break-up so the surface still has
 * texture when the camera sits low. Both amplitudes are deliberately small —
 * enough to kill the flatness, not enough to compete with the landmark the
 * player is walking towards.
 */
/**
 * The underside of an island.
 *
 * The islands used to be a 1.2-unit cylinder, which reads as a plate someone
 * laid on the sky rather than as ground that continues below the horizon. This
 * builds a tapering, eroded chunk instead, so the silhouette carries the same
 * faceted low-poly language as the landmarks.
 *
 * It is safe to put this below the walkable disc because the region is a 2D
 * navigation problem: `navigation.ts` clamps the player to `radius - 1.2`
 * with a further 1.1 margin, so across every region radius in the catalog the
 * furthest a player can stand is 94.9% of the way out. The profile below
 * starts at 95.5%, which leaves a margin on the largest region. Nothing here
 * is ever stood on, so it can be as dramatic as it likes.
 */
function buildCliff(id: string, radius: number, stone: string): THREE.BufferGeometry {
  const seed = [...id].reduce((acc, ch) => acc + ch.charCodeAt(0), 0) * 0.017;

  // (radius fraction, depth). The first ring matches the ground disc's outer
  // edge so there is no visible gap between them; the rest taper to a point,
  // which is what makes it read as something torn loose rather than cut.
  //
  // The second ring *rises* slightly before falling. The player stands at
  // y=0 with the camera above it, so a cliff that only ever descends stays
  // entirely below the eyeline and the island keeps a hard flat silhouette
  // against the sky — which is exactly what it looked like before this
  // profile existed. Breaking the rim upward by a fraction of a unit is what
  // makes the edge read as an edge.
  const PROFILE: [number, number][] = [
    [0.985, 0.35],
    [1.0, 0.05],
    [1.01, -1.0],
    [0.98, -2.3],
    [0.91, -3.8],
    [0.79, -5.3],
    [0.62, -6.6],
    [0.41, -7.7],
    [0.2, -8.5],
  ];

  // Enough sectors to actually resolve the lobes below. They are sums of the
  // 3rd, 7th and 11th harmonics, and at 44 sectors the 11th got four samples per
  // cycle — it aliased into a beat pattern that had nothing to do with the
  // intended silhouette. 96 puts ~8.7 samples on that shortest cycle.
  const SECTORS = 96;
  const positions: number[] = [];
  const colors: number[] = [];
  const base = new THREE.Color(stone);
  const deep = base.clone().offsetHSL(-0.01, 0.02, -0.16);
  const c = new THREE.Color();

  // Per-region radius wobble, so no two islands share a silhouette. Sampled
  // around the circumference and reused per sector, which keeps the columns
  // continuous instead of jittering ring to ring.
  const lobes = new Float32Array(SECTORS);
  for (let s = 0; s < SECTORS; s += 1) {
    const angle = (s / SECTORS) * Math.PI * 2;
    lobes[s] =
      Math.sin(angle * 3 + seed * 9) * 0.5 +
      Math.sin(angle * 7 - seed * 4) * 0.3 +
      Math.sin(angle * 11 + seed * 2) * 0.2;
  }

  const ringStart: number[] = [];
  for (let r = 0; r < PROFILE.length; r += 1) {
    const [radiusFrac, y] = PROFILE[r];
    ringStart.push(positions.length / 3);
    for (let s = 0; s < SECTORS; s += 1) {
      const angle = (s / SECTORS) * Math.PI * 2;
      // Erosion grows with depth: the top edge stays true to the walkable
      // disc, and the underside wanders as it falls away.
      const erosion = lobes[s] * (0.035 + 0.075 * (r / (PROFILE.length - 1)));
      const ringRadius = radius * (radiusFrac + erosion);
      positions.push(Math.cos(angle) * ringRadius, y, Math.sin(angle) * ringRadius);

      const depth = 1 - r / (PROFILE.length - 1);
      c.copy(base).lerp(deep, depth * 0.85);
      // Ambient occlusion by hand: the deeper parts of the underside are the
      // least exposed to the sky and should read as the darkest thing on the
      // island.
      c.multiplyScalar(1 - depth * 0.3);
      colors.push(c.r, c.g, c.b);
    }
  }
  ringStart.push(positions.length / 3);

  // Apex, so the chunk closes rather than ending in an open ring.
  const apex = positions.length / 3;
  const lowest = PROFILE[PROFILE.length - 1];
  positions.push(0, lowest[1] - radius * 0.06, 0);
  c.copy(deep).multiplyScalar(0.62);
  colors.push(c.r, c.g, c.b);

  const indices: number[] = [];
  for (let r = 0; r < PROFILE.length - 1; r += 1) {
    for (let s = 0; s < SECTORS; s += 1) {
      const s2 = (s + 1) % SECTORS;
      const a = ringStart[r] + s;
      const b = ringStart[r] + s2;
      const d = ringStart[r + 1] + s;
      const e = ringStart[r + 1] + s2;
      indices.push(a, d, e, a, e, b);
    }
  }
  const last = ringStart[PROFILE.length - 1];
  for (let s = 0; s < SECTORS; s += 1) {
    indices.push(last + s, apex, last + ((s + 1) % SECTORS));
  }

  const geo = new THREE.BufferGeometry();
  geo.setAttribute('position', new THREE.Float32BufferAttribute(positions, 3));
  geo.setAttribute('color', new THREE.Float32BufferAttribute(colors, 3));
  geo.setIndex(indices);
  geo.computeVertexNormals();
  return geo;
}

/**
 * A flat disc with real radial subdivision.
 *
 * `CircleGeometry` is a fan: one centre vertex and a single rim ring, so its
 * vertex colours can only vary *angularly* and never *radially*. Measured on
 * the running build, a 68-unit disc had 66 vertices, which puts a wedge about
 * 3.3 units wide at the rim — any colour feature smaller than that cannot be
 * represented at all, however the colour is computed. Concentric rings are what
 * the ground's mottling actually needs.
 */

export function TerrainDisc({ region }: { region: RegionDef }) {
  const [normalMap, roughnessMap] = useTexture([NORMAL_MAP_URL, ROUGH_MAP_URL]);

  // Both maps are data, not colour, so they must not be sRGB-decoded — that
  // would skew the normals and visibly flatten the relief.
  useEffect(() => {
    normalMap.colorSpace = THREE.NoColorSpace;
    roughnessMap.colorSpace = THREE.NoColorSpace;
    for (const map of [normalMap, roughnessMap]) {
      map.wrapS = THREE.RepeatWrapping;
      map.wrapT = THREE.RepeatWrapping;
      map.anisotropy = 8;
      map.needsUpdate = true;
    }
  }, [normalMap, roughnessMap]);

  const geometry = useMemo(() => {
    // Density is tied to the radius so every island's mottling reads at the
    // same physical scale instead of the hub looking coarser than the rest.
    const segments = Math.max(96, Math.round(region.radius * 3.6));
    const geo = buildDisc(region.radius, segments, 12);
    const positions = geo.getAttribute('position');
    const colors = new Float32Array(positions.count * 3);

    // Planar UVs from world XZ. The disc is flat, so a single projection is
    // exactly correct here and the texture tiles evenly all the way out.
    const uvs = new Float32Array(positions.count * 2);
    for (let i = 0; i < positions.count; i += 1) {
      uvs[i * 2] = positions.getX(i) / GROUND_TILE_SIZE;
      uvs[i * 2 + 1] = positions.getZ(i) / GROUND_TILE_SIZE;
    }

    // Each region gets its own seed, derived from its own name, so the tint is
    // stable across reloads without being identical between neighbours.
    const seed = [...region.id].reduce((acc, ch) => acc + ch.charCodeAt(0), 0) * 0.017;

    const base = new THREE.Color(region.palette.stone);
    const warm = base.clone().offsetHSL(0.012, 0.04, 0.05);
    const cool = base.clone().offsetHSL(-0.02, -0.02, -0.07);
    const c = new THREE.Color();

    for (let i = 0; i < positions.count; i += 1) {
      // Local space: the disc is built at the origin and moved by its group.
      const x = positions.getX(i);
      const z = positions.getZ(i);

      const broad =
        Math.sin(x * 0.035 + seed) * Math.cos(z * 0.031 - seed * 0.7) +
        Math.sin((x + z) * 0.017 + seed * 1.3) * 0.6;
      // The band the old fan could not reach: ~12 and ~7 unit wavelengths, which
      // is where a ground reads as ground rather than as a painted disc. It is
      // only expressible now that the mesh has concentric rings.
      const mid =
        Math.sin(x * 0.41 + seed * 3.1) * Math.sin(z * 0.47 - seed * 2.3) +
        Math.sin((x - z) * 0.63 - seed * 1.1) * 0.6;
      const fine = Math.sin(x * 0.21 + seed * 2.1) * Math.sin(z * 0.19 - seed * 1.7) * 0.35;

      const t = THREE.MathUtils.clamp(0.5 + (broad + mid * 0.5 + fine) * 0.22, 0, 1);
      c.copy(cool).lerp(warm, t);

      // Darken toward the rim. The edge of a disc is the one place a player
      // looks straight down, and a bright lip there reads as a wall of light.
      const distance = Math.hypot(x, z) / region.radius;
      c.multiplyScalar(1 - THREE.MathUtils.smoothstep(distance, 0.7, 1.0) * 0.34);

      colors[i * 3] = c.r;
      colors[i * 3 + 1] = c.g;
      colors[i * 3 + 2] = c.b;
    }

    geo.setAttribute('color', new THREE.BufferAttribute(colors, 3));
    geo.setAttribute('uv', new THREE.BufferAttribute(uvs, 2));
    return geo;
  }, [region.id, region.palette.stone, region.radius]);

  // The builder takes its inputs explicitly rather than the whole region
  // object. `region` is a fresh object every render, so depending on it would
  // rebuild the cliff mesh on every frame; depending on the three fields it
  // actually reads is both correct and what the lint rule is asking for.
  const { id: cliffSeedId, radius: cliffRadius, palette: cliffPalette } = region;
  const cliffStone = cliffPalette.stone;
  const cliff = useMemo(
    () => buildCliff(cliffSeedId, cliffRadius, cliffStone),
    [cliffSeedId, cliffRadius, cliffStone],
  );

  return (
    <>
      <mesh geometry={cliff} receiveShadow castShadow>
        {/* No normal map here, and flat shading is deliberate: the cliff is
            the one surface whose faceting reads as rock. A normal map on a
            flat-shaded face would be contradictory anyway. */}
        <meshStandardMaterial
          vertexColors
          flatShading
          roughness={0.94}
          metalness={0}
          side={THREE.DoubleSide}
        />
      </mesh>

      <mesh geometry={geometry} receiveShadow>
        <meshStandardMaterial
          vertexColors
          // Deliberately NOT flatShading: three.js derives flat-shaded normals
          // from the face, which bypasses the normal map entirely — the ground
          // would look exactly as it did before. The disc's top is genuinely flat
          // anyway, so smooth shading costs nothing and lets the map through.
          roughness={0.96}
          metalness={0}
          normalMap={normalMap}
          // The value the map was measured at. See `GROUND_NORMAL_SCALE` for
          // why this is a constant and why it used to be unreadable.
          normalScale={GROUND_NORMAL_SCALE_VECTOR}
          roughnessMap={roughnessMap}
        />
      </mesh>
    </>
  );
}